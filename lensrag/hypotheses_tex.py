"""Write the hypothesis results (H1-H3) as a standalone LaTeX document.

Everything in the document, including each verdict sentence, is generated from the run's own
files (hypotheses.json, run_config.json, answers_config.json, answers.csv), so rerunning the
experiment and this step keeps the write-up and the numbers in step. Tables use booktabs, like
the project report (docs/report/corpus-rag-project.tex), so they can be copied across.
"""
from __future__ import annotations
import json
import math
from datetime import date
from pathlib import Path
import numpy as np
import pandas as pd

METHOD_NAMES = {"bm25_topk": "BM25 top-$k$", "hybrid_topk": "Hybrid top-$k$", "lensrag": "LensRAG",
                "lensrag_rerank": "LensRAG + judge", "long_context_128k": "Long context 128k",
                "long_context_1m": "Long context 1M", "long_context_full": "Long context (full)",
                "rag_topk": "Standard RAG (top-$k$)"}


def esc(x) -> str:
    s = str(x)
    for a, b in [("\\", r"\textbackslash{}"), ("&", r"\&"), ("%", r"\%"), ("#", r"\#"), ("_", r"\_"),
                 ("{", r"\{"), ("}", r"\}"), ("~", r"\textasciitilde{}"), ("^", r"\textasciicircum{}")]:
        s = s.replace(a, b)
    return s


def num(x, nd=3):
    if x is None or (isinstance(x, float) and math.isnan(x)):
        return "--"
    return f"{x:.{nd}f}"


def pval(p):
    if p is None or (isinstance(p, float) and math.isnan(p)):
        return "--"
    return "$<0.001$" if p < 0.001 else f"{p:.3f}"


def ci(c):
    return f"[{num(c[0])}, {num(c[1])}]" if c and c[0] is not None else "--"


def name(m):
    return METHOD_NAMES.get(m, esc(m))


def table(caption, label, cols, header, rows, note=None):
    out = [r"\begin{table}[htbp]", r"\centering\small", rf"\caption{{{caption}}}", rf"\label{{{label}}}",
           rf"\begin{{tabular}}{{{cols}}}", r"\toprule", " & ".join(header) + r" \\", r"\midrule"]
    out += [" & ".join(str(c) for c in r) + r" \\" for r in rows]
    out += [r"\bottomrule", r"\end{tabular}"]
    if note:
        out += [rf"\par\smallskip\parbox{{0.95\linewidth}}{{\footnotesize {note}}}"]
    out += [r"\end{table}", ""]
    return out


def _load(path):
    try:
        return json.loads(Path(path).read_text())
    except Exception:
        return {}


# --- answer-level paired comparison ---------------------------------------------------------
def answer_comparison(answers: pd.DataFrame | None, ours="lensrag", baseline="rag_topk", seed=42):
    """Paired exact-match comparison per scope: mean difference, bootstrap CI, exact sign test."""
    if answers is None or answers.empty or not {ours, baseline} <= set(answers.method):
        return []
    from scipy.stats import binomtest
    ok = answers[answers.error.isna() | (answers.error.astype(str) == "")] if "error" in answers else answers
    rows = []
    for scope in ("global", "local"):
        a = ok[(ok.method == ours) & (ok.scope == scope)].set_index("qid").exact_match
        b = ok[(ok.method == baseline) & (ok.scope == scope)].set_index("qid").exact_match
        common = a.dropna().index.intersection(b.dropna().index)  # free-text answers have no exact match
        if len(common) == 0:
            continue
        d = (a[common] - b[common]).astype(float).values
        rng = np.random.default_rng(seed)
        boots = sorted(rng.choice(d, len(d)).mean() for _ in range(2000))
        wins, losses = int((d > 0).sum()), int((d < 0).sum())
        p = binomtest(wins, wins + losses, 0.5, alternative="greater").pvalue if wins + losses else float("nan")
        rows.append({"scope": scope, "n": len(d), "ours": float(a[common].mean()), "baseline": float(b[common].mean()),
                     "diff": float(d.mean()), "ci": (boots[50], boots[1949]), "wins": wins, "losses": losses, "p": p})
    return rows


# --- document ---------------------------------------------------------------------------------
def build(result: dict, run_config: dict, answers_config: dict, answers: pd.DataFrame | None) -> str:
    s = result.get("settings", {})
    alpha = s.get("alpha", 0.05)
    L = [r"\documentclass[11pt]{article}", r"\usepackage[margin=1in]{geometry}", r"\usepackage{booktabs}",
         r"\usepackage{amsmath}", r"\usepackage{hyperref}", r"\usepackage[T1]{fontenc}",
         r"\title{LensRAG: Hypothesis Results (H1--H3)}",
         rf"\author{{Generated by \texttt{{lensrag/hypotheses\_tex.py}} from \texttt{{results/}}}}",
         rf"\date{{{date.today().isoformat()}}}", r"\begin{document}", r"\maketitle", ""]

    # Setup
    stats = run_config.get("corpus_stats", {})
    L += [r"\section{Experimental setup}", ""]
    L += [r"The experiment evaluates LensRAG on the BragsLabs HR corpus at three cumulative sizes and against the 89 gold "
          r"questions of the benchmark (report Section~3.3). Retrieval-level metrics score whether the gold evidence documents "
          r"reach the context (document-level recall, precision and F1); answer-level metrics score the answers themselves "
          r"(exact match with a 1\% numeric tolerance, set-level F1, and, for sampled estimates, whether the gold value lies "
          r"inside the 95\% interval).", ""]
    if stats:
        L += table("Corpus tiers.", "tab:tiers", "lrrr", ["Tier", "Documents", "Words", r"Tokens (\texttt{cl100k})"],
                   [[t, f"{v['documents']:,}", f"{v['words']:,}", f"{v['tokens']:,}"] for t, v in stats.items()])
    comps = answers_config.get("lensrag_components") or {}
    judge = run_config.get("relevance_judge") or {}
    rows = [["Dense embeddings (retrieval benchmark)", esc(run_config.get("embedding_model") or run_config.get("semantic", "tfidf"))],
            ["Relevance judge (LensRAG + judge)", esc(f"{judge.get('model')} (threshold {judge.get('threshold')})") if judge else "--"]]
    llm = answers_config.get("llm_model")
    if llm:
        for part in str(llm).split(" / "):
            role, _, model = part.partition("=")
            rows.append([f"LLM role: {esc(role)}", esc(model or role)])
    for k, label in [("reranker_model", "Reranker (local questions)"), ("spacy_model", "Entity NER"),
                     ("nli_model", "NLI verification"), ("sentiment_model", "Per-record sentiment")]:
        if comps.get(k):
            rows.append([label, esc(comps[k])])
    if answers_config.get("rag_topk_retrieval"):
        rows.append(["Standard RAG retrieval (answer level)", esc(answers_config["rag_topk_retrieval"])])
    L += table("Models and settings used in this run.", "tab:models", "ll", ["Component", "Model / setting"], rows,
               note=rf"Statistics: one-sided tests at $\alpha={alpha}$ with Holm correction within each hypothesis; "
                    rf"95\% bootstrap intervals ({s.get('bootstrap', 2000)} resamples, seed {s.get('seed', 42)}). "
                    rf"Platform: {esc(run_config.get('platform', ''))}.")

    # H1
    h1 = [r for r in result.get("h1", []) if r["metric"] == "evidence_recall"]
    sup = sorted({r["tier"] for r in h1 if r["significant"]})
    L += [r"\section{H1: standard RAG on global versus local questions}", "",
          r"\textbf{Hypothesis.} Standard top-$k$ RAG scores significantly lower on global than on local questions; "
          r"long-context prompting narrows the gap when the corpus fits the window but degrades as the corpus grows.", ""]
    L += table("H1: evidence recall of standard RAG, local minus global (retrieval level). $p$: one-sided Mann--Whitney U, Holm-corrected.",
               "tab:h1", "llrrrlll", ["Tier", "Method", "Local", "Global", "Gap", "95\\% CI", "$p$", "Supported"],
               [[r["tier"], name(r["method"]), num(r["local"]), num(r["global"]), num(r["gap"]), ci(r["ci"]),
                 pval(r["p_holm"]), "yes" if r["significant"] else "no"] for r in sorted(h1, key=lambda x: (x["tier"], x["method"]))])
    lc = result.get("h1_long_context", [])
    if lc:
        L += table("H1: long-context prompting, whole documents packed in corpus order. Recall here asks whether the gold evidence fits in the window at all.",
                   "tab:h1lc", "llrrrrr", ["Method", "Tier", "Corpus docs", "Docs in context", "Context tokens", "Global recall", "Local recall"],
                   [[name(r["method"]), r["tier"], r["corpus_docs"], r["docs_in_context"], f"{r['context_tokens']:,}",
                     num(r["global_recall"]), num(r["local_recall"])] for r in lc])
    lc128 = {r["tier"]: r["global_recall"] for r in lc if r["method"] == "long_context_128k"}
    verdict = (f"supported on tier{'s' if len(sup) > 1 else ''} {', '.join(sup)}" if sup else "not supported on any tier")
    L += [rf"\textbf{{Verdict.}} The gap in evidence recall is {verdict} at the retrieval level. "
          + (rf"Long-context prompting with a 128k window reaches global recall {num(lc128.get('S'))} on tier S but "
             rf"{num(lc128.get('M'))} on M and {num(lc128.get('L'))} on L, consistent with degradation once the corpus "
             r"exceeds the window. " if lc128 else "")
          + r"Whether a model uses evidence that is present in a long context is not measured here.", ""]

    # H2
    h2 = [r for r in result.get("h2", []) if r["baseline"] in ("bm25_topk", "hybrid_topk", "long_context_128k", "long_context_1m")]
    L += [r"\section{H2: LensRAG versus the baselines}", "",
          r"\textbf{Hypothesis.} The routed pipeline achieves higher set-level F1 and exact-match accuracy on global questions "
          r"than all baselines, without reducing accuracy on local questions.", ""]
    L += table("H2 (retrieval level): global questions, paired over the same questions. $p$: one-sided Wilcoxon signed-rank, Holm-corrected.",
               "tab:h2", "lllrrrlll", ["Tier", "Ours", "Baseline", "Ours F1", "Base F1", "Diff", "95\\% CI", "$p$", "Supported"],
               [[r["tier"], name(r["ours"]), name(r["baseline"]), num(r["ours_mean"]), num(r["baseline_mean"]), num(r["diff"]),
                 ci(r["ci"]), pval(r["p_holm"]), "yes" if r["significant"] else "no"]
                for r in h2 if r["metric"] == "evidence_f1"])
    nonin = result.get("h2_local_noninferiority", [])
    if nonin:
        margin = s.get("noninferiority_margin", 0.05)
        L += table(rf"H2 (retrieval level): local questions, recall of ours minus the best standard RAG baseline. Non-inferior when the CI lower bound exceeds $-{margin}$.",
                   "tab:h2local", "lllrrll", ["Tier", "Ours", "Baseline", "$n$", "Diff", "95\\% CI", "Non-inferior"],
                   [[r["tier"], name(r["ours"]), name(r["baseline"]), r["n"], num(r["diff"]), ci(r["ci"]),
                     "yes" if r["non_inferior"] else "no"] for r in nonin])
    cost = [r for r in result.get("h2_cost", []) if r["tier"] == "L"]
    if cost:
        L += table("Cost on tier L: mean tokens of context per question and retrieval latency on this machine.", "tab:cost", "llrrr",
                   ["Method", "Scope", "Context tokens", "p50 ms", "p95 ms"],
                   [[name(r["method"]), r["scope"], f"{r['context_tokens']:,.0f}", num(r["latency_p50"], 1), num(r["latency_p95"], 1)]
                    for r in cost])
    ans = result.get("answer_level") or []
    comp = answer_comparison(answers)
    if ans:
        L += table("H2 (answer level), tier L. Interval coverage applies to answers LensRAG estimated from a sample.", "tab:h2ans",
                   "llrrrrrr", ["Method", "Scope", "$n$", "Exact match", "Set F1", "Interval cov.", "Tokens", "p50 s"],
                   [[name(r["method"]), r["scope"], r["n"], num(r["exact_match"]), num(r["set_f1"]),
                     num(r.get("interval_coverage")) if r.get("n_interval") else "--", f"{r['tokens']:,.0f}", num(r["latency_s"], 1)]
                    for r in ans])
    if comp:
        L += table("H2 (answer level): exact match, LensRAG minus standard RAG, paired by question. $p$: one-sided exact sign test.",
                   "tab:h2pair", "lrrrrlrrl", ["Scope", "$n$", "LensRAG", "Std RAG", "Diff", "95\\% CI", "Wins", "Losses", "$p$"],
                   [[r["scope"], r["n"], num(r["ours"]), num(r["baseline"]), num(r["diff"]), ci(r["ci"]), r["wins"], r["losses"], pval(r["p"])]
                    for r in comp])
    sig = {(r["tier"], r["ours"]) for r in h2 if r["metric"] == "evidence_f1" and r["significant"]}
    tiers_all = sorted({r["tier"] for r in h2 if r["ours"] == "lensrag" and r["metric"] == "evidence_f1"
                        and all(((x["tier"], "lensrag") in sig and x["significant"]) for x in h2
                                if x["tier"] == r["tier"] and x["ours"] == "lensrag" and x["metric"] == "evidence_f1"
                                and x["baseline"] in ("bm25_topk", "hybrid_topk"))})
    text = (rf"\textbf{{Verdict.}} At the retrieval level, LensRAG's evidence F1 on global questions is significantly higher "
            rf"than both standard RAG baselines on tier{'s' if len(tiers_all) > 1 else ''} {', '.join(tiers_all) or 'none'}. ")
    g = next((r for r in comp if r["scope"] == "global"), None)
    lo = next((r for r in comp if r["scope"] == "local"), None)
    if g:
        text += (rf"At the answer level on tier L, LensRAG's exact match on global questions is {num(g['ours'])} against "
                 rf"{num(g['baseline'])} for standard RAG (difference {num(g['diff'])}, 95\% CI {ci(g['ci'])}, "
                 rf"sign test $p={pval(g['p']).strip('$')}$), which "
                 + ("supports" if g["p"] < alpha and g["diff"] > 0 else "does not support")
                 + r" the global part of H2. ")
        if lo:
            text += (rf"On local questions the difference is {num(lo['diff'])} (95\% CI {ci(lo['ci'])}), so LensRAG "
                     + ("does not reduce" if lo["ci"][0] > -s.get("noninferiority_margin", 0.05) else "may reduce")
                     + r" local accuracy beyond the non-inferiority margin. ")
    else:
        text += r"Answer-level exact match and set F1 were not measured in this run (no LLM configured). "
    L += [text, ""]

    # H3
    h3 = result.get("h3_completeness", [])
    L += [r"\section{H3: completeness and conflict checks}", "",
          r"\textbf{Hypothesis.} Completeness and conflict checks flag a majority of incomplete or conflicting answers with a "
          r"low false-alarm rate.", ""]
    if h3:
        L += table("H3: completeness flags of the coverage loop (LensRAG + judge, global questions). An answer is incomplete when a gold evidence document was not retrieved.",
                   "tab:h3", "lrrrrrrr", ["Tier", "Global qs", "Incomplete", "Flagged", "Detection", "Complete", "Flagged", "False alarm"],
                   [[r["tier"], r["n"], r["incomplete"], r["flagged_incomplete"], num(r["detection_rate"]), r["complete"],
                     r["flagged_complete"], num(r["false_alarm_rate"])] for r in h3])
    conf = [r for r in result.get("h3_conflict_evidence", []) if r["method"] in ("lensrag", "lensrag_rerank", "bm25_topk")]
    if conf:
        L += table("H3: conflict questions, share where every document needed to see the conflict was retrieved.", "tab:h3conf",
                   "llrrr", ["Tier", "Method", "$n$", "All evidence retrieved", "Recall"],
                   [[r["tier"], name(r["method"]), r["n"], num(r["all_evidence_retrieved"]), num(r["evidence_recall"])] for r in conf])
    ok = [r["tier"] for r in h3 if (r.get("detection_rate") or 0) > 0.5 and (r.get("false_alarm_rate") or 1) < 0.2]
    L += [rf"\textbf{{Verdict.}} The completeness check {'meets' if ok else 'does not meet'} the H3 criterion "
          r"(detection above 0.5 with false alarms below 0.2)"
          + (rf" on tier{'s' if len(ok) > 1 else ''} {', '.join(ok)}" if ok else " on any tier")
          + r". Conflict-flag precision and recall need LLM-extracted values and a labelled conflict set; this run reports "
            r"only whether the evidence needed to see each conflict was retrieved.", ""]

    # Limitations
    L += [r"\section{Limitations}", "", r"\begin{itemize}",
          r"\item The benchmark has 89 questions (17 local, all from tier S), so the local-versus-global comparison on tiers M and L compares different kinds of documents.",
          r"\item The rule-based planner and the relevance-judge thresholds were developed on the same benchmark; only the BGE reranker threshold was chosen on a held-out split.",
          r"\item Retrieval-level metrics are a precondition for correct answers, not answer accuracy.",
          r"\item Exact match uses a 1\% tolerance, so sampled estimates can miss it while their interval still covers the gold value.",
          r"\item Local models were Qwen2.5 3B/14B/32B in place of the 72B models in Table~3.1, which do not fit in 36\,GB of memory." if "qwen" in str(llm).lower() else
          r"\item Results describe the specific models listed in Table~\ref{tab:models}.",
          r"\end{itemize}", "", r"\end{document}", ""]
    return "\n".join(L)


def write_tex(result: dict, results_dir, tex_path):
    results_dir = Path(results_dir)
    answers = pd.read_csv(results_dir / "answers.csv") if (results_dir / "answers.csv").exists() else None
    text = build(result, _load(results_dir / "run_config.json"), _load(results_dir / "answers_config.json"), answers)
    Path(tex_path).parent.mkdir(parents=True, exist_ok=True)
    Path(tex_path).write_text(text, encoding="utf-8")
    return tex_path
